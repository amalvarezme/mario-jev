"""The reproducibility proof: two fed runs, same seed and fixed source, act alike.

The property T3 exists to pin, end to end through the CLI rather than through a
unit: with ``rollout_cost_source=fixed``, the same seed and the same transcript,
two runs produce **identical action sequences** -- compared field by field, with
only the genuine measurements excluded. The second test is the negative control
that keeps the first honest: with the default ``measured`` source fed two
different injected clock readings, the horizon moves, and the same comparison
fails. The proof is therefore falsifiable rather than vacuous.

Nothing here sleeps and nothing here slows the machine: the clock is the
planner's own ``time`` module replaced by an advancing fake, the move
``tests/test_trajectory.py`` established for the fixed cost source. The
transcript itself is generated by a real run against a scripted transport, so the
fed runs replay real recorded answers rather than a hand-built fixture; the fed
runs then patch every client factory to raise, proving the flag opened no socket.

This module imports no other test file: the doubles are local, which is the
convention this suite already follows.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Callable, Mapping

import pytest

from mario_jev import cli
from mario_jev.jev import HttpResult, JevClient
from mario_jev.journal import Journal, read_journal
from mario_jev.trajectory import planner as planner_module

#: A synthetic credential. It is never a real key and is never printed.
SENTINEL_KEY = "apikey_SENTINEL_repro_do_not_leak"

#: The two fixed figures a clock-free horizon is sized from. They are the same
#: values ``tests/test_trajectory.py`` uses, and they are deliberately not the
#: measured cost of any machine: the point is that the horizon stops depending on
#: one.
FIXED_BASE_MS = 0.5
FIXED_PER_FRAME_MS = 1.1


class _Responder:
    """A scripted Jev transport that answers the real questions with a real body.

    ``confidence`` is what the recorded answer claims. The default is above the
    settings' 0.6 threshold, so a replay of it *applies* the recorded action; the
    negative control records below the threshold instead, which makes the rollout
    table -- and therefore the clock-fitted horizon -- decide the action.
    """

    def __init__(self, *, confidence: float = 0.9) -> None:
        self.calls = 0
        self._confidence = float(confidence)

    def __call__(self, request: object) -> HttpResult:
        self.calls += 1
        questions = request.json_body["questions"]  # type: ignore[attr-defined]
        choice = next(iter(questions["best_action"]["criteria"]))
        body = json.dumps(
            {
                "model": "jev-test",
                "answers": {
                    "best_action": {
                        "type": "choice",
                        "choice": choice,
                        "confidence": self._confidence,
                        "probabilities": {choice: 0.7, "NOOP": 0.3},
                    },
                    "risk": {
                        "type": "score",
                        "score": 0.2,
                        "confidence": 0.9,
                        "legend": {"0": "safe"},
                        "probabilities": {"0": 1.0},
                    },
                    "lethal_ahead": {"type": "noul", "noul": 0.1},
                    "gap_severity": {
                        "type": "score",
                        "score": 0.0,
                        "confidence": 0.9,
                        "legend": {"0": "no gap"},
                        "probabilities": {"0": 1.0},
                    },
                },
                "usage": {"input_tokens": 5, "output_tokens": 5},
            }
        )
        return HttpResult(status=200, body=body, elapsed_ms=3.0)


def _client_with(settings, responder: _Responder) -> JevClient:
    return JevClient(
        endpoint=settings.jev_endpoint,
        model=settings.jev_model,
        api_key=settings.jev_api_key,
        timeout_s=settings.jev_timeout_s,
        max_attempts=1,
        transport=responder,
        sleeper=lambda delay: None,
    )


def _explode(*args: object, **kwargs: object) -> object:
    raise AssertionError("a fed run must not build or enter a Jev client")


def _set_cost_env(monkeypatch: pytest.MonkeyPatch, *, cost_source: str) -> None:
    """The settings both the recording and the replay run under.

    ``MARIO_SEED`` is pinned to 0 explicitly rather than left to the default, so
    "the same seed" is a value this module states rather than inherits.
    """
    monkeypatch.setenv("MARIO_DECISION_CADENCE", "1")
    monkeypatch.setenv("MARIO_SEED", "0")
    monkeypatch.setenv("MARIO_ROLLOUT_COST_SOURCE", cost_source)
    monkeypatch.setenv("MARIO_ROLLOUT_FIXED_BASE_MS", str(FIXED_BASE_MS))
    monkeypatch.setenv("MARIO_ROLLOUT_FIXED_PER_FRAME_MS", str(FIXED_PER_FRAME_MS))


def _run_live_recording(
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
    *,
    cost_source: str,
    max_ticks: int,
    confidence: float = 0.9,
) -> Path:
    """Record a transcript with a real run over the scripted transport."""
    _set_cost_env(monkeypatch, cost_source=cost_source)
    monkeypatch.setenv("JEV_API_KEY", SENTINEL_KEY)
    responder = _Responder(confidence=confidence)
    monkeypatch.setattr(
        cli, "_build_client", lambda settings: _client_with(settings, responder)
    )
    transcript = tmp_path / "transcript.jsonl"
    code = cli.main(
        [
            "run",
            "--journal",
            str(transcript),
            "--artifacts-dir",
            str(tmp_path / "transcript-artifacts"),
            "--fast",
            "--max-ticks",
            str(max_ticks),
        ]
    )
    assert code == 0
    assert responder.calls >= 1
    return transcript


def _run_fed(
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
    transcript: Path,
    *,
    cost_source: str,
    name: str,
    max_ticks: int,
) -> Path:
    """Replay ``transcript`` into a new journal, with no client and no credential."""
    _set_cost_env(monkeypatch, cost_source=cost_source)
    # No credential: a fed run does not need one, and a live fallback must be
    # impossible. Both the CLI factory and the loop's own client construction are
    # made fatal, so if the replay fell through to the live path this would fail
    # loudly instead of opening a socket.
    monkeypatch.delenv("JEV_API_KEY", raising=False)
    monkeypatch.setattr(cli, "_build_client", _explode)
    journal = tmp_path / name
    code = cli.main(
        [
            "run",
            "--answers",
            str(transcript),
            "--journal",
            str(journal),
            "--artifacts-dir",
            str(tmp_path / f"{name}-artifacts"),
            "--fast",
            "--max-ticks",
            str(max_ticks),
        ]
    )
    assert code == 0
    return journal


class _AdvancingClock:
    """A stand-in for the planner's ``time`` module.

    Only ``perf_counter`` is read by the planner. Each read advances the clock by
    ``step_ms``, so a tiny step models a fast machine and a huge one models a
    machine far slower than any figure the settings would configure. This is the
    same double ``tests/test_trajectory.py`` uses; nothing sleeps.
    """

    def __init__(self, step_ms: float) -> None:
        self._now = 0.0
        self._step_s = float(step_ms) / 1000.0

    def perf_counter(self) -> float:
        now = self._now
        self._now += self._step_s
        return now


#: The genuine measurements of the replaying machine, and therefore the *only*
#: exclusions from the field-by-field comparison. Each is a wall-clock reading (a
#: tick's phase times, the sweep's own elapsed/sweep cost) or a cost model fitted
#: from one. ``calibration_frames`` is the number of emulator steps the measured
#: calibration spent, which is itself the size of a measurement. Everything left
#: -- the horizons, the candidate rows, the decisions, the applied answers -- is a
#: decision input or an outcome, and must match.
_MEASURED_TICK_KEYS = ("latencies_ms",)
_MEASURED_ROLLOUT_KEYS = (
    "elapsed_ms",
    "sweep_ms",
    "base_ms",
    "per_frame_ms",
    "calibration_frames",
)
_MEASURED_SUMMARY_KEYS = ("elapsed_s", "decision_rate_hz")


def _replay_view(journal: Journal) -> dict[str, object]:
    """Everything decision-relevant in a journal, without the machine's measurements.

    The comparison is field by field rather than action-only, and the names of
    the exclusions are stated here rather than implied: two runs whose *decisions*
    match but whose horizons, candidate risks or applied-answer ages differ are
    not the same run, and a proof that compared only the chosen action would miss
    that. The excluded keys are the only fields a clock is allowed to move.
    """
    ticks: list[dict[str, object]] = []
    for tick in journal.ticks:
        view = dict(tick)
        for key in _MEASURED_TICK_KEYS:
            view.pop(key, None)
        rollout = view.get("rollout")
        if isinstance(rollout, Mapping):
            stripped = dict(rollout)
            for key in _MEASURED_ROLLOUT_KEYS:
                stripped.pop(key, None)
            view["rollout"] = stripped
        ticks.append(view)
    summary = dict(journal.summary or {})
    for key in _MEASURED_SUMMARY_KEYS:
        summary.pop(key, None)
    return {"ticks": ticks, "summary": summary}


def test_the_same_seed_transcript_and_fixed_source_reproduce_the_action_sequence(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    transcript = _run_live_recording(
        monkeypatch, tmp_path, cost_source="fixed", max_ticks=12
    )
    first = _run_fed(
        monkeypatch,
        tmp_path,
        transcript,
        cost_source="fixed",
        name="first.jsonl",
        max_ticks=6,
    )
    second = _run_fed(
        monkeypatch,
        tmp_path,
        transcript,
        cost_source="fixed",
        name="second.jsonl",
        max_ticks=6,
    )

    first_journal = read_journal(first)
    second_journal = read_journal(second)

    # The proof: every decision-relevant field matches, field by field.
    assert _replay_view(first_journal) == _replay_view(second_journal)

    # And the equality is not "both runs did nothing": the transcript was replayed
    # with no exhaustion and no mismatch, and Jev's own answers reached the ticks.
    assert first_journal.ticks
    assert first_journal.summary["degradations"].get("answers_exhausted", 0) == 0
    assert first_journal.summary["degradations"].get("transcript_mismatch", 0) == 0
    assert first_journal.summary["answers_applied"] >= 1
    assert any(
        tick["decision"]["source"] in {"jev", "jev_stale"}
        for tick in first_journal.ticks
    )
    # Every tick of a fed run says so, so the identical sequence cannot be read as
    # a measurement of a live call.
    assert all(
        "transcript_answers" in tick["degradations"] for tick in first_journal.ticks
    )


def test_the_measured_horizon_moves_with_the_clock_so_the_proof_can_fail(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    # A recording longer than the replay: the recording's *last* fired call may
    # still be in flight when it stopped, so it has no applied answer, and a
    # replay cut to the same length would exhaust on that tail. The extra answers
    # are unused tail, which is the honest shape of a transcript replayed shorter
    # than it was recorded. The recorded answers sit *below* the confidence
    # threshold on purpose: a confident recorded choice would be executed as-is
    # and mask the horizon change, while a below-threshold one falls to the
    # rollout, whose horizon is exactly what the clock moves.
    transcript = _run_live_recording(
        monkeypatch, tmp_path, cost_source="measured", max_ticks=12, confidence=0.5
    )

    # Two readings of the same setup under the default measured source: a fast
    # machine and an absurdly slow one, injected rather than waited for.
    monkeypatch.setattr(planner_module, "time", _AdvancingClock(0.003))
    fast = _run_fed(
        monkeypatch,
        tmp_path,
        transcript,
        cost_source="measured",
        name="fast.jsonl",
        max_ticks=6,
    )
    monkeypatch.setattr(planner_module, "time", _AdvancingClock(3000.0))
    absurd = _run_fed(
        monkeypatch,
        tmp_path,
        transcript,
        cost_source="measured",
        name="absurd.jsonl",
        max_ticks=6,
    )

    fast_journal = read_journal(fast)
    absurd_journal = read_journal(absurd)

    fast_horizons = [tick["rollout"]["horizon"] for tick in fast_journal.ticks]
    absurd_horizons = [tick["rollout"]["horizon"] for tick in absurd_journal.ticks]
    fast_actions = [tick["decision"]["action"] for tick in fast_journal.ticks]
    absurd_actions = [tick["decision"]["action"] for tick in absurd_journal.ticks]

    # The horizon is a decision input, not one of the excluded measurements, and
    # the action moved with it -- so the equality the positive test proves is a
    # property of the fixed source, not of the comparison being unable to fail.
    assert fast_horizons != absurd_horizons
    assert fast_actions != absurd_actions
    assert _replay_view(fast_journal) != _replay_view(absurd_journal)
